// Generates vui/palette.odin from Tailwind v4 theme variables (CSS lab(), D50) -> sRGB hex.
import fs from 'node:fs';
const vars = JSON.parse(fs.readFileSync(new URL('./tailwind-vars.json', import.meta.url)));
function lab2srgb(L, a, b) {
  const fy = (L + 16) / 116, fx = fy + a / 500, fz = fy - b / 200;
  const e = 216/24389, k = 24389/27;
  const xr = fx**3 > e ? fx**3 : (116*fx-16)/k, yr = L > k*e ? fy**3 : L/k, zr = fz**3 > e ? fz**3 : (116*fz-16)/k;
  const X = xr*0.96422, Y = yr, Z = zr*0.82521; // D50
  // Bradford D50 -> D65
  const X2 =  0.9554734527042182*X - 0.023098536874261423*Y + 0.0632593086610217*Z;
  const Y2 = -0.028369706963208136*X + 1.0099954580058226*Y + 0.021041398966943008*Z;
  const Z2 =  0.012314001688319899*X - 0.020507696433477912*Y + 1.3303659366080753*Z;
  let r =  3.2409699419045226*X2 - 1.537383177570094*Y2 - 0.4986107602930034*Z2;
  let g = -0.9692436362808796*X2 + 1.8759675015077202*Y2 + 0.04155505740717559*Z2;
  let bb = 0.05563007969699366*X2 - 0.20397695888897652*Y2 + 1.0569715142428786*Z2;
  const enc = v => { v = Math.min(1, Math.max(0, v)); return v <= 0.0031308 ? 12.92*v : 1.055*Math.pow(v, 1/2.4) - 0.055; };
  return [r, g, bb].map(v => Math.round(enc(v)*255));
}
const hex = n => n.toString(16).padStart(2, '0');
const families = []; const byFam = {};
for (const [k, v] of Object.entries(vars)) {
  const m = k.match(/^--color-([a-z]+)-(\d+)$/); if (!m) continue;
  const lm = v.match(/lab\(([\d.\-]+)%\s+([\d.\-]+)\s+([\d.\-]+)\)/); if (!lm) continue;
  const [r,g,b] = lab2srgb(+lm[1], +lm[2], +lm[3]);
  if (!byFam[m[1]]) { byFam[m[1]] = []; families.push(m[1]); }
  byFam[m[1]].push([+m[2], `0x${hex(r)}${hex(g)}${hex(b)}`]);
}
const shades = [50,100,200,300,400,500,600,700,800,900,950];
let out = `// Code generated by tools/gen/palette.mjs from Tailwind CSS v4 theme variables. DO NOT EDIT.
// Source colors are CSS lab() (D50); converted to sRGB and clipped to gamut.
package vui

PALETTE_SHADES :: [11]int{${shades.join(', ')}}

Palette_Family :: struct {
	name:   string,
	shades: [11]u32, // 0xRRGGBB for 50..950
}

PALETTE := [?]Palette_Family{
`;
for (const f of families) {
  const m = Object.fromEntries(byFam[f]);
  out += `\t{"${f}", {${shades.map(s => m[s]).join(', ')}}},\n`;
}
out += `}\n`;
fs.writeFileSync(new URL('../../vui/palette.odin', import.meta.url), out);
console.log(families.length, 'families');

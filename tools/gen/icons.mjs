// Generates vui/icons/heroicons.odin from tools/gen/heroicons/*.svg (Heroicons 20 solid, MIT).
import fs from 'node:fs';
const dir = new URL('./heroicons/', import.meta.url);
const files = fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
let out = `// Code generated by tools/gen/icons.mjs. DO NOT EDIT.
// Heroicons (20px solid) by Tailwind Labs, MIT License. https://github.com/tailwindlabs/heroicons
package vui_icons

import vui ".."

`;
const names = [];
for (const f of files) {
  const svg = fs.readFileSync(new URL(f, dir), 'utf8');
  const vb = svg.match(/viewBox="([\d.\s-]+)"/)[1].split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path([^>]*)\/?>/g)].map(m => {
    const d = m[1].match(/\sd="([^"]+)"/)[1];
    const eo = /fill-rule="evenodd"/.test(m[1]);
    return { d, eo };
  });
  const id = f.replace('.svg', '').replace(/-/g, '_').toUpperCase();
  names.push([id, f.replace('.svg', '')]);
  out += `${id}_PATHS := [?]vui.Icon_Path{\n` + paths.map(p => `\t{d = "${p.d}", even_odd = ${p.eo}},\n`).join('') + `}\n`;
}
out += `\nIcons :: struct {\n` + names.map(([id]) => `\t${id.toLowerCase()}: vui.Icon,\n`).join('') + `}\n\n`;
out += `// Registers every icon with the context and returns the handles.\nregister :: proc(ctx: ^vui.Context) -> (ic: Icons) {\n`;
for (const [id, name] of names) out += `\tic.${id.toLowerCase()} = vui.icon_register(ctx, "${name}", {20, 20}, ${id}_PATHS[:])\n`;
out += `\treturn\n}\n`;
fs.writeFileSync(new URL('../../vui/icons/heroicons.odin', import.meta.url), out);
fs.copyFileSync(new URL('LICENSE', dir), new URL('../../vui/icons/HEROICONS_LICENSE', import.meta.url));
console.log(names.length, 'icons');

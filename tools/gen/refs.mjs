// Generates showroom/ref_data.odin: page list + class reference tables mirroring the
// Tailwind CSS docs structure (Tailwind CSS is MIT licensed). Source: tailwind-docs.json,
// scraped from tailwindcss.com by the showroom maintainers' tooling.
import fs from 'node:fs';
const nav = JSON.parse(fs.readFileSync(new URL('./tailwind-nav.json', import.meta.url)));
const docs = JSON.parse(fs.readFileSync(new URL('./tailwind-docs.json', import.meta.url)));
const skip = new Set(['Getting started', 'Core concepts', 'Base styles']);
const clean = (css) => {
  css = css.replace(/\s*\n\s*/g, ' ');
  // prefer the literal value from the trailing comment over var(--token)
  css = css.replace(/var\((--[a-z0-9-]+)\);\s*\/\*\s*([^*]+?)\s*\*\//g, (m, v, val) => /oklch|calc\(var/.test(val) ? `${v.replace('--', '')} token;` : `${val};`);
  css = css.replace(/\/\*[^*]*\*\//g, '').replace(/\s+/g, ' ').trim();
  return css;
};
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let out = `// Code generated by tools/gen/refs.mjs. DO NOT EDIT.
package showroom

Ref_Page :: struct {
	group: string,
	slug:  string,
	title: string,
	desc:  string,
	rows:  string, // "class\\teffect\\n" lines
}

REF_PAGES := [?]Ref_Page{
`;
let n = 0;
for (const g of nav) {
  if (skip.has(g.g)) continue;
  for (const l of g.links) {
    const d = docs[l.h]; if (!d) continue;
    const slug = l.h.replace('/docs/', '');
    const rows = (d.rows || []).filter(r => r.length >= 2 && !/custom-property|\(<|--tw-/.test(r[0])).slice(0, 160).map(r => `${r[0]}\t${clean(r[1])}`).join('\n');
    out += `\t{"${esc(g.g)}", "${slug}", "${esc(l.t)}", "${esc(d.desc || '')}", "${esc(rows).replace(/\n/g, '\\n').replace(/\t/g, '\\t')}"},\n`;
    n++;
  }
}
out += `}\n`;
fs.writeFileSync(new URL('../../showroom/ref_data.odin', import.meta.url), out);
console.log(n, 'pages');
